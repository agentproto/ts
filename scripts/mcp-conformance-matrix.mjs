#!/usr/bin/env node
/**
 * Generate `docs/mcp-conformance-matrix.md` from the `_conformance` blocks of the MCP conformance fixtures
 * (`packages/runtime/src/__tests__/fixtures/mcp-2026-07-28/` and `.../mcp-skills-ext-beta/`), the same blocks
 * `mcp-conformance-blackbox.test.ts` replays against a live `/mcp`. A fixture without a block is not in the matrix.
 *
 *   node scripts/mcp-conformance-matrix.mjs           write the page
 *   node scripts/mcp-conformance-matrix.mjs --check   exit 1 when the committed page differs from the fixtures
 *
 * Deterministic: file-name order, then case order; no date, no environment.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs"
import { join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const FIXTURES = join(ROOT, "packages/runtime/src/__tests__/fixtures")
const DIRS = ["mcp-2026-07-28", "mcp-skills-ext-beta"]
const OUT = join(ROOT, "docs/mcp-conformance-matrix.md")
const SURFACES = ["gateway", "elicitation", "tasks", "skills"]

/** Every `_conformance` case, in replay order, with the file it comes from. */
export function collectCases(fixturesDir = FIXTURES) {
  const cases = []
  for (const dir of DIRS) {
    const abs = join(fixturesDir, dir)
    for (const file of readdirSync(abs).filter(f => f.endsWith(".json")).sort()) {
      const json = JSON.parse(readFileSync(join(abs, file), "utf8"))
      if (!Array.isArray(json._conformance)) continue
      for (const c of json._conformance) cases.push({ ...c, file: `${dir}/${file}`, source: json._source })
    }
  }
  return cases
}

const cell = text => String(text).replace(/\|/g, "\\|").replace(/\n/g, " ")
const expected = c => {
  const e = c.expect ?? {}
  const base = e.code !== undefined ? `HTTP ${e.httpStatus}, \`${e.code}\`` : `HTTP ${e.httpStatus}, \`${e.resultType}\``
  return c.knownDefect ? `${base} (known defect)` : base
}
const uniq = list => [...new Set(list)]

export function renderMatrix(cases) {
  const methods = []
  for (const surface of SURFACES) {
    for (const method of uniq(cases.filter(c => c.surface === surface).map(c => c.method)).sort()) methods.push({ surface, method })
  }
  const lines = [
    "# MCP conformance matrix",
    "",
    "<!-- Generated by `node scripts/mcp-conformance-matrix.mjs` from the `_conformance` blocks of the fixtures. Do not edit by hand. -->",
    "",
    "What `/mcp` answers in protocol `2026-07-28`, per method, as replayed by",
    "`packages/runtime/src/__tests__/mcp-conformance-blackbox.test.ts` against a live server. Each case comes from a",
    "fixture whose `_source` is a public page (the MCP specification `2026-07-28`, SEP-2663 for Tasks, the Skills",
    "extension overview); a shape the page does not show is marked \"reconstructed from the text\" in the fixture.",
    "",
    "Fixtures without a `_conformance` block are not replayed and do not appear here (today: the Events extension",
    "fixtures, and the two hand-written Skills result shapes). The page that explains each surface is",
    "[`mcp-modern-gateway.md`](./mcp-modern-gateway.md).",
    "",
    "## By method",
    "",
    "| Method | Surface | Era | Capability required | Positive cases | Negative cases | Codes |",
    "|---|---|---|---|---|---|---|",
  ]
  for (const { surface, method } of methods) {
    const all = cases.filter(c => c.surface === surface && c.method === method)
    const pos = all.filter(c => c.case === "positive")
    const neg = all.filter(c => c.case === "negative")
    const era = uniq(all.map(c => c.era)).join(", ")
    const caps = uniq(pos.map(c => c.capability)).join("; ") || "none (no positive case: the method is not served)"
    const codes = uniq(all.map(expected)).join("; ")
    lines.push(
      `| \`${method}\` | ${surface} | ${cell(era)} | ${cell(caps)} | ${pos.length} | ${neg.length} | ${cell(codes)} |`,
    )
  }
  lines.push("", "## Every case", "")
  for (const surface of SURFACES) {
    const own = cases.filter(c => c.surface === surface)
    if (own.length === 0) continue
    lines.push(`### ${surface}`, "", "| Method | Case | What is checked | Capability | Expected | Fixture |", "|---|---|---|---|---|---|")
    for (const c of own) {
      lines.push(`| \`${c.method}\` | ${c.case} | ${cell(c.title)} | ${cell(c.capability)} | ${expected(c)} | \`${c.file}\` |`)
    }
    lines.push("")
  }
  const defects = cases.filter(c => c.knownDefect)
  if (defects.length > 0) {
    lines.push("## Known defects", "", "Cases whose expected status is the one AIP-77 gives, not the one the code answers today. The", "replay checks everything else about them and pins the status with an expected failure, which turns red once fixed.", "")
    for (const note of uniq(defects.map(c => c.knownDefect))) {
      const own = defects.filter(c => c.knownDefect === note)
      lines.push(`- ${note} Cases: ${uniq(own.map(c => `\`${c.method}\``)).join(", ")} (${own.length}).`)
    }
    lines.push("")
  }
  lines.push("## Sources", "")
  for (const source of uniq(cases.map(c => c.source)).sort()) lines.push(`- ${source}`)
  lines.push("")
  return lines.join("\n")
}

function main() {
  const rendered = renderMatrix(collectCases())
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
    if (current !== rendered) {
      console.error(`${relative(ROOT, OUT)} is out of date with the fixtures: run node scripts/mcp-conformance-matrix.mjs`)
      process.exit(1)
    }
    console.log(`${relative(ROOT, OUT)} matches the fixtures`)
    return
  }
  writeFileSync(OUT, rendered)
  console.log(`wrote ${relative(ROOT, OUT)}`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
