#!/usr/bin/env node
/**
 * gen-spec-packages-doc.mjs: generates docs/reference/spec-packages.md, one
 * row per package in the `spec-reference` tier (the packages that only
 * implement an AIP file format), classified by scripts/gen-status.mjs.
 *
 * The doc is never edited by hand and never checked in per PR: the
 * spec-packages-doc workflow regenerates it on push to main and opens or
 * updates a single bot PR when it changed.
 *
 * AIP column, in order, blank when neither source is unambiguous:
 *   1. `src/schema.ts` header "Generated from `resources/aip-<n>/...`"
 *   2. `package.json` keywords, when exactly one `aip-<n>` keyword exists
 * Descriptions are not used: they routinely name neighbouring AIPs.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { computeStatus } from "./gen-status.mjs";

const OUTFILE = "docs/reference/spec-packages.md";
const SCHEMA_HEADER_RE = /Generated from\s+(?:\*\s*)?`?resources\/aip-(\d+)\//;

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

export function deriveAip(root, dir, pj) {
  const schemaPath = path.join(root, dir, "src", "schema.ts");
  if (existsSync(schemaPath)) {
    const m = readFileSync(schemaPath, "utf8").match(SCHEMA_HEADER_RE);
    if (m) return `AIP-${m[1]}`;
  }
  const fromKeywords = new Set();
  for (const k of pj.keywords ?? []) {
    const m = /^aip-(\d+)$/i.exec(k);
    if (m) fromKeywords.add(m[1]);
  }
  return fromKeywords.size === 1 ? `AIP-${[...fromKeywords][0]}` : "";
}

function oneLine(text) {
  const flat = String(text ?? "").replace(/\s+/g, " ").trim();
  const cell = flat.replace(/\|/g, "\\|");
  const firstSentence = cell.match(/^(.+?\.)(?:\s|$)/);
  return firstSentence ? firstSentence[1] : cell;
}

export function specPackageRows(root = process.cwd()) {
  return computeStatus(root)
    .filter((e) => e.tier === "spec-reference")
    .map((e) => {
      const pj = readJson(path.join(root, e.dir, "package.json"));
      return {
        name: e.name,
        dir: e.dir,
        aip: deriveAip(root, e.dir, pj),
        version: pj.version ?? "",
        description: oneLine(pj.description),
      };
    })
    .sort((a, b) => a.dir.localeCompare(b.dir));
}

export function generateSpecPackagesDoc(rows) {
  const table = [
    "| Package | Path | AIP | Version | Description |",
    "|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| ${r.name} | \`${r.dir}\` | ${r.aip} | ${r.version} | ${r.description} |`,
    ),
  ].join("\n");
  return `<!-- This file is generated by scripts/gen-spec-packages-doc.mjs and refreshed by the spec-packages-doc workflow. Do not edit by hand. -->

# Spec reference packages

Packages in the \`spec-reference\` tier: reference implementations of AIP file formats, whose workspace dependencies are limited to the doctype meta-factory, the generic doctype verbs and build tooling (see \`scripts/gen-status.mjs\` for the classification). The AIP column is read from the package's generated \`src/schema.ts\` header, or from a single \`aip-<n>\` keyword in its \`package.json\`; it is blank when neither says.

${table}
`;
}

function main() {
  const markdown = generateSpecPackagesDoc(specPackageRows());
  mkdirSync(path.dirname(OUTFILE), { recursive: true });
  writeFileSync(OUTFILE, markdown);
  console.log(`wrote ${OUTFILE}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
