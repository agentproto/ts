// Renders the AIP-64 pack that ships this catalog (pack/) from the in-code
// entries. The entries stay the content; pack/ is generated, never hand-edited.
// A drift test (src/__tests__/pack.test.ts) fails when pack/ and the entries
// disagree. Run after `pnpm build`: `pnpm render:pack`.
import { mkdir, rm, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import matter from "gray-matter"
import { BUILTIN_ROLE_ENTRIES } from "../dist/index.mjs"

const PACK_VERSION = "1.0.0"
const root = join(dirname(fileURLToPath(import.meta.url)), "..", "pack")

const clean = (value) => JSON.parse(JSON.stringify(value))

await rm(join(root, "roles"), { recursive: true, force: true })
await mkdir(join(root, "skills"), { recursive: true })
await writeFile(join(root, "skills", ".gitkeep"), "")

const entries = [...BUILTIN_ROLE_ENTRIES].sort((a, b) => a.slug.localeCompare(b.slug))
for (const entry of entries) {
  const dir = join(root, "roles", entry.slug)
  await mkdir(dir, { recursive: true })
  await writeFile(join(dir, "ROLE.md"), matter.stringify(entry.body ?? "", clean(entry.handle)))
}

const packFrontmatter = {
  schema: "pack/v1",
  name: "role-catalog",
  title: "Role catalog",
  description:
    "The AIP-47 starter roles shipped by @agentproto/role-catalog, as catalog members of a pack. Installing it makes each role resolvable by ref and binds nothing.",
  version: PACK_VERSION,
  plugin: { inline: true },
  roles: entries.map((e) => ({ path: `./roles/${e.slug}/ROLE.md` })),
}
await writeFile(
  join(root, "PACK.md"),
  matter.stringify(
    [
      "# Role catalog",
      "",
      "Generated by `scripts/render-pack.mjs` from the in-code entries of `@agentproto/role-catalog`. Do not edit by hand.",
      "",
      "`plugin.inline: true` with an empty `./skills/` directory is how this pack satisfies the `pack/v1` rule that a plugin must be resolvable (AIP-64 §Plugin): the pack carries catalog members only and no skills.",
      "",
    ].join("\n"),
    packFrontmatter,
  ),
)
console.log(`rendered ${entries.length} roles into ${root}`)
