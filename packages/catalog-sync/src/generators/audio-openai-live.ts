/**
 * audio-openai-live generator — reads the pinned OpenAI `/v1/models`
 * snapshot and emits the live/realtime audio-engine roster for
 * @agentproto/model-catalog.
 *
 * The LLM generators (`llm-openrouter.ts`, …) made LLM ids self-syncing:
 * the committed `*.generated.ts` artifact drifts in a reviewable PR whenever
 * the provider's model list moves. Audio/live models had no such half —
 * their ids were hand-curated in `model-catalog/src/audio/catalog.ts` and
 * drifted silently (the `gpt-live-1.1` / `gemini-3.8-live` refreshes of
 * 2026-11-20/22 were manual finds). This generator gives live/realtime
 * engines the same auto-sync treatment:
 *
 *   - SNAPSHOT-FIRST, like every generator: offline runs read the committed
 *     `snapshots/audio-openai-live.json`; `--refresh` re-fetches
 *     `https://api.openai.com/v1/models` (authed, `OPENAI_API_KEY`) and
 *     re-pins it before generating. Tests and CI never touch the network.
 *   - IDS ONLY on the generated side: `/v1/models` carries no capabilities
 *     and no pricing, so those are NOT invented here. The curated
 *     `AUDIO_MODEL_CATALOG` stays the curation overlay; each emitted entry
 *     carries a `needsCuration` flag that is true while no curated entry
 *     claims the id (`openaiLiveIdsNeedingCuration()` surfaces the debt).
 *
 * Id filter (`isLiveAudioId`): realtime + live session engines only —
 * `*realtime*` (the `/v1/realtime` API family, including the legacy
 * `gpt-4o-realtime-*` ids) and `*live*` (the `/v1/live/sessions` GPT-Live
 * family). Date-pinned variants (`*-YYYY-MM-DD`, e.g.
 * `gpt-realtime-2025-08-28`) are dropped: they are frozen snapshots of a
 * rolling id the roster already carries, and would only add churn.
 */

import { z } from "zod"

import {
  isoDateFromUnixSeconds,
} from "../added-at.js"
import {
  defineGenerator,
  type GeneratedFiles,
  type GeneratorContext,
} from "../types.js"
import { AUDIO_MODEL_CATALOG } from "@agentproto/model-catalog/audio"

/** Pinned OpenAI models list — ids are authoritative, prices are not here. */
const OPENAI_MODELS_URL = "https://api.openai.com/v1/models"

/** Committed drop-in for @agentproto/model-catalog's audio subpath. */
const OUTPUT_PATH = "packages/model-catalog/src/audio/openai-live.generated.ts"

/** Session-engine families: /v1/realtime + /v1/live (incl. gpt-4o-realtime-*). */
const LIVE_ID_RE = /realtime|live/

/** Date-pinned snapshots of a rolling id (`gpt-realtime-2025-08-28`) — churn. */
const DATE_PINNED_RE = /-\d{4}-\d{2}-\d{2}$/

/** True for OpenAI live/realtime audio session-engine ids. */
export function isLiveAudioId(id: string): boolean {
  return LIVE_ID_RE.test(id) && !DATE_PINNED_RE.test(id)
}

// ── Source schema ────────────────────────────────────────────────────────
// `/v1/models` payload shape (verified against the live API, 2026-11-22):
// `data[]` carries `id`, `created` (unix seconds), `owned_by`, and — on
// newer rows — `shutdown_date` (ISO or null). passthrough() keeps unknown
// fields forward-compatible without a regenerate.
const ModelSchema = z
  .object({
    id: z.string(),
    created: z.number().optional(),
    owned_by: z.string().optional(),
    shutdown_date: z.string().nullable().optional(),
  })
  .passthrough()

const SnapshotSchema = z
  .object({
    object: z.string().optional(),
    data: z.array(ModelSchema),
  })
  .passthrough()

// ── Output shape (mirrors model-catalog's AudioLiveModelEntry) ────────────

/** OpenAI's own `owned_by` provenance + the curation flag — see live.ts. */
interface AudioLiveEntry {
  providerId: string
  modality: "audio"
  kind: "live"
  needsCuration: boolean
  ownedBy?: string
  createdAt?: string
  shutdownDate?: string
}

// ── Serialization ────────────────────────────────────────────────────────

function serializeEntry(e: AudioLiveEntry): string {
  const lines: string[] = [`  ${JSON.stringify(e.providerId)}: {`]
  lines.push(`    providerId: ${JSON.stringify(e.providerId)},`)
  lines.push(`    modality: "audio",`)
  lines.push(`    kind: "live",`)
  lines.push(`    needsCuration: ${e.needsCuration},`)
  if (e.ownedBy !== undefined) {
    lines.push(`    ownedBy: ${JSON.stringify(e.ownedBy)},`)
  }
  if (e.createdAt !== undefined) {
    lines.push(`    createdAt: ${JSON.stringify(e.createdAt)},`)
  }
  if (e.shutdownDate !== undefined) {
    lines.push(`    shutdownDate: ${JSON.stringify(e.shutdownDate)},`)
  }
  lines.push("  },")
  return lines.join("\n")
}

function serializeFile(entries: Record<string, AudioLiveEntry>): string {
  const ids = Object.keys(entries).sort()
  const lines: string[] = [
    "// AUTO-GENERATED by @agentproto/catalog-sync (audio:openai-live).",
    "// Do not edit by hand - re-run `pnpm --filter @agentproto/catalog-sync generate`.",
    `// Source: ${OPENAI_MODELS_URL} (pinned snapshot: snapshots/audio-openai-live.json)`,
    "//",
    "// Live/realtime audio session-engine roster: OpenAI's own id list,",
    "// filtered to the *realtime* and *live* families. `/v1/models` publishes",
    "// ids only - capabilities and pricing are the CURATED overlay",
    "// (packages/model-catalog/src/audio/catalog.ts). `needsCuration` is true",
    "// while no curated entry claims the id (see audio/live.ts).",
    "// Date-pinned variants (*-YYYY-MM-DD) of rolling ids are intentionally excluded.",
    "",
    'import type { AudioLiveModelEntry } from "./live.js"',
    "",
    "export const OPENAI_LIVE_MODELS: Record<string, AudioLiveModelEntry> = {",
  ]
  for (const id of ids) lines.push(serializeEntry(entries[id]!))
  lines.push("}")
  lines.push("")
  return lines.join("\n")
}

// ── Generator ────────────────────────────────────────────────────────────

/**
 * The source. `id` MUST match the snapshot filename stem — the framework's
 * `ctx.fetchSource` resolves `snapshots/<id>.json`.
 */
export const AUDIO_OPENAI_LIVE_SOURCE = {
  id: "audio-openai-live",
  url: OPENAI_MODELS_URL,
  // Live refresh needs the account key; offline reads ignore this. A missing
  // key degrades to the committed snapshot (never an unauthenticated fetch).
  headers: { Authorization: "Bearer env:OPENAI_API_KEY" },
}

async function generate(ctx: GeneratorContext): Promise<GeneratedFiles> {
  const parsed = SnapshotSchema.parse(
    await ctx.fetchSource(AUDIO_OPENAI_LIVE_SOURCE),
  )

  // The curation overlay: curated provider ids decide `needsCuration`.
  const curatedProviderIds = new Set(
    Object.values(AUDIO_MODEL_CATALOG)
      .filter(m => m.provider === "openai")
      .map(m => m.providerId),
  )

  const entries: Record<string, AudioLiveEntry> = {}
  for (const model of parsed.data) {
    if (!isLiveAudioId(model.id)) continue
    entries[model.id] = {
      providerId: model.id,
      modality: "audio",
      kind: "live",
      needsCuration: !curatedProviderIds.has(model.id),
      ownedBy: model.owned_by,
      createdAt:
        model.created !== undefined
          ? isoDateFromUnixSeconds(model.created)
          : undefined,
      shutdownDate: model.shutdown_date ?? undefined,
    }
  }

  return {
    [OUTPUT_PATH]: serializeFile(entries),
  }
}

export const audioOpenAILive = defineGenerator({
  name: "audio:openai-live",
  modality: "audio",
  sources: [AUDIO_OPENAI_LIVE_SOURCE],
  generate,
})
