/**
 * media-openrouter generators - OpenRouter's media routes, priced per output
 * token (`pricing.image_output`, e.g. `openai/gpt-image-1` = 0.00004).
 *
 * OpenRouter is the only cross-vendor route catalog that exposes a machine
 * readable media price list, so it is the JSON-source counterpart to the
 * HTML-scraped Replicate pages (`scripts/catalog-sync/sync-replicate.mjs`).
 *
 * IMPORTANT: image routes are billed PER OUTPUT TOKEN. We record that number
 * with `unit: "per_token"` and never derive a per-image price (the token count
 * per image is model- and resolution-dependent; inventing one would be wrong).
 * Routes whose media prices are all zero are skipped entirely - no `0` entry.
 */

import { z } from "zod"

import { defineGenerator, type GeneratedFiles, type GeneratorContext } from "../types.js"
import {
  type FetchedAtLedger,
  fetchedAtLedgerRelPath,
  hashJson,
  readFetchedAtLedger,
  resolveFetchedAt,
  serializeFetchedAtLedger,
} from "../fetched-at.mjs"
import { todayIso } from "../added-at.js"

const OPENROUTER_IMAGE_URL =
  "https://openrouter.ai/api/v1/models?output_modalities=image"
const OPENROUTER_VIDEO_URL =
  "https://openrouter.ai/api/v1/models?output_modalities=video"

const PricingSchema = z
  .object({
    image_output: z.string().optional(),
    video_output: z.string().optional(),
  })
  .passthrough()

const ModelSchema = z
  .object({
    id: z.string(),
    pricing: PricingSchema.optional(),
  })
  .passthrough()

const SnapshotSchema = z.object({
  data: z.array(ModelSchema),
})

interface MediaPricingEntry {
  unit: "per_token"
  priceUsd: number
  source: "openrouter"
  fetchedAt: string
}

function round9(n: number): number {
  return Math.round(n * 1_000_000_000) / 1_000_000_000
}

/** A positive per-token price, or undefined for absent/zero/unparseable. */
function perToken(raw: string | undefined): number | undefined {
  if (raw === undefined) return undefined
  const n = Number(raw)
  if (!Number.isFinite(n) || n <= 0) return undefined
  return round9(n)
}

function serializeFile(
  constName: string,
  generatorName: string,
  sourceUrl: string,
  priceField: string,
  entries: Record<string, MediaPricingEntry>
): string {
  const ids = Object.keys(entries).sort()
  const lines: string[] = [
    `// AUTO-GENERATED by @agentproto/catalog-sync (${generatorName}).`,
    "// Do not edit by hand - re-run `pnpm --filter @agentproto/catalog-sync generate`.",
    `// Source: ${sourceUrl}`,
    `// Prices are USD per output token (\`pricing.${priceField}\`), unit per_token.`,
    "// Routes whose media prices are zero are omitted rather than emitted as 0.",
    "",
    'import type { MediaPricing } from "../pricing/media.js"',
    "",
    `export const ${constName}: Record<string, MediaPricing> = {`,
  ]
  for (const id of ids) {
    const e = entries[id]!
    lines.push(
      `  ${JSON.stringify(id)}: { unit: "per_token", priceUsd: ${e.priceUsd}, source: "openrouter", fetchedAt: ${JSON.stringify(e.fetchedAt)} },`
    )
  }
  lines.push("}")
  lines.push("")
  return lines.join("\n")
}

interface OpenRouterSpec {
  generatorName: string
  sourceId: string
  url: string
  outputPath: string
  constName: string
  ledgerId: string
  priceField: "image_output" | "video_output"
}

async function generate(ctx: GeneratorContext, spec: OpenRouterSpec): Promise<GeneratedFiles> {
  const source = { id: spec.sourceId, url: spec.url }
  const payload = await ctx.fetchSource(source)
  const parsed = SnapshotSchema.parse(payload)

  const today = todayIso()
  const previous = readFetchedAtLedger(spec.ledgerId)
  const ledger: FetchedAtLedger = {}

  const entries: Record<string, MediaPricingEntry> = {}
  for (const model of parsed.data) {
    const priceUsd = perToken(model.pricing?.[spec.priceField])
    if (priceUsd === undefined) continue
    const { entry } = resolveFetchedAt(
      previous,
      model.id,
      hashJson({ unit: "per_token", priceUsd }),
      today
    )
    ledger[model.id] = entry
    entries[model.id] = {
      unit: "per_token",
      priceUsd,
      source: "openrouter",
      fetchedAt: entry.fetchedAt,
    }
  }

  return {
    [spec.outputPath]: serializeFile(
        spec.constName,
        spec.generatorName,
        spec.url,
        spec.priceField,
        entries
      ),
    [fetchedAtLedgerRelPath(spec.ledgerId)]: serializeFetchedAtLedger(ledger),
  }
}

export const mediaOpenRouterImage = defineGenerator({
  name: "image:openrouter",
  modality: "image",
  sources: [{ id: "media-openrouter-image", url: OPENROUTER_IMAGE_URL }],
  generate: ctx =>
    generate(ctx, {
      generatorName: "image:openrouter",
      sourceId: "media-openrouter-image",
      url: OPENROUTER_IMAGE_URL,
      outputPath: "packages/model-catalog/src/image/openrouter-pricing.generated.ts",
      constName: "OPENROUTER_IMAGE_PRICING",
      ledgerId: "media-openrouter-image",
      priceField: "image_output",
    }),
})

