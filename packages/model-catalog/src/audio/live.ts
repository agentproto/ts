/**
 * Live/realtime audio session engines — the auto-synced side of the audio
 * catalog.
 *
 * Before this module, every audio/live model id (openai `gpt-realtime`,
 * `gpt-live`, google `gemini-*-live`) was hand-curated end to end in
 * `catalog.ts` and drifted silently as providers shipped or retired models.
 * The LLM halves of the catalog already had the other arrangement: ids come
 * in from a synced `*.generated.ts` file (regenerated from a pinned provider
 * snapshot by `@agentproto/catalog-sync`, weekly, via
 * `.github/workflows/catalog-sync.yml`) and humans only overlay the parts the
 * provider does not publish (capabilities, pricing).
 *
 * Audio/live gets the same split here:
 *   - `openai-live.generated.ts` — AUTO-SYNCED. The OpenAI `/v1/models` id
 *     roster (realtime/live family only), regenerated by the
 *     `audio:openai-live` generator. Id drift lands in a reviewable sync PR.
 *   - `catalog.ts` — CURATED OVERLAY. `AUDIO_MODEL_CATALOG` keeps supplying
 *     capabilities + pricing: what a model DOES and COSTS is opinionated
 *     billing data, and `/v1/models` carries neither capabilities nor prices,
 *     so they are never fabricated on the generated side.
 *
 * The bridge between the two halves is the `needsCuration` flag each
 * generated entry carries: true while no curated `AUDIO_MODEL_CATALOG` entry
 * claims that provider id, so a freshly synced id reads as curation debt in
 * the sync PR diff instead of appearing silently.
 */

import { AUDIO_MODEL_CATALOG } from "./catalog.js"
import { OPENAI_LIVE_MODELS } from "./openai-live.generated.js"

// The synced roster re-exported from its generated home, so consumers have
// one import site for the whole live bridge.
export { OPENAI_LIVE_MODELS } from "./openai-live.generated.js"

/**
 * One auto-synced live/realtime audio engine. Generated by the
 * `audio:openai-live` generator (`packages/catalog-sync`) from the pinned
 * OpenAI `/v1/models` snapshot; never hand-edited.
 */
export interface AudioLiveModelEntry {
  /** Provider-native model id — the string OpenAI's API accepts. */
  providerId: string
  /** Catalog modality — speech-driven audio session engines. */
  modality: "audio"
  /**
   * Engine family — live/realtime SESSION engines (`/v1/realtime`,
   * `/v1/live/sessions`), as opposed to a cascade `stt`+`tts` pair.
   */
  kind: "live"
  /**
   * Curation flag. `/v1/models` publishes ids only — capabilities and
   * pricing live in the curated overlay (`AUDIO_MODEL_CATALOG`). True while
   * no curated entry carries this provider id: the id is synced but its
   * capabilities/cost still need a human entry in `audio/catalog.ts`.
   */
  needsCuration: boolean
  /** OpenAI's own `owned_by` for the model (provenance). */
  ownedBy?: string
  /** ISO date OpenAI created the model id (`created`, unix seconds). */
  createdAt?: string
  /**
   * ISO date OpenAI announces as the model's earliest shutdown
   * (`shutdown_date`), when the provider exposes one.
   */
  shutdownDate?: string
}

/** Every synced OpenAI live/realtime id, in provider order (sorted). */
export const OPENAI_LIVE_MODEL_IDS: readonly string[] = Object.keys(
  OPENAI_LIVE_MODELS,
)

/**
 * Curated OpenAI provider ids — the capabilities/pricing overlay. Derived
 * from `AUDIO_MODEL_CATALOG`, never hand-maintained: adding a curated entry
 * is what flips a generated id's `needsCuration` to false.
 */
export const CURATED_OPENAI_AUDIO_PROVIDER_IDS: readonly string[] =
  Object.values(AUDIO_MODEL_CATALOG)
    .filter(m => m.provider === "openai")
    .map(m => m.providerId)

/** True when a curated `AUDIO_MODEL_CATALOG` entry claims this provider id. */
export function isCuratedOpenAIAudioModel(providerId: string): boolean {
  return CURATED_OPENAI_AUDIO_PROVIDER_IDS.includes(providerId)
}

/**
 * Synced live/realtime ids that still lack a curated overlay entry
 * (capabilities + pricing) — the open curation debt, in sync order.
 */
export function openaiLiveIdsNeedingCuration(): readonly string[] {
  return OPENAI_LIVE_MODEL_IDS.filter(id => !isCuratedOpenAIAudioModel(id))
}
